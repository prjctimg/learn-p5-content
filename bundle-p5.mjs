#!/usr/bin/env node
// Bundles the pinned p5.js distribution into a string literal for the app.
// Produces two files:
//   - ./p5Source.ts   (the minified p5 library as a string literal)
//   - ./p5Version.ts  (the resolved version string)

import fs from "fs";
import path from "path";
import https from "https";
import { fileURLToPath } from "url";
import { PINNED_P5_VERSION } from "./p5-version.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = __dirname;

const P5_SOURCE_FILE = path.join(ROOT, "./p5Source.ts");
const P5_VERSION_FILE = path.join(ROOT, "./p5Version.ts");
const CDN_URL = `https://cdn.jsdelivr.net/npm/p5@${PINNED_P5_VERSION}/lib/p5.min.js`;

function download(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, (res) => {
        if (res.statusCode && res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
          return download(res.headers.location).then(resolve).catch(reject);
        }
        if (res.statusCode !== 200) {
          return reject(new Error(`HTTP ${res.statusCode} fetching ${url}`));
        }
        const chunks = [];
        res.on("data", (d) => chunks.push(d));
        res.on("end", () => resolve(Buffer.concat(chunks).toString("utf8")));
      })
      .on("error", reject);
  });
}

function writeP5Source(src) {
  const escaped = src.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  const chunks = [];
  const max = 8192;
  for (let i = 0; i < escaped.length; i += max) {
    chunks.push(escaped.slice(i, i + max));
  }
  const arr = chunks.map((c, i) => `  _p[${i}] = \`${c}\`;`).join("\n");
  const file = `// Auto-generated by scripts/bundle-p5.mjs. Do not edit.\n// Pinned p5.js version: ${PINNED_P5_VERSION}\nconst _p: string[] = [];\n${arr}\nexport const p5Source: string = _p.join("");\n`;
  fs.writeFileSync(P5_SOURCE_FILE, file, "utf-8");
}

function writeP5Version(version) {
  const file = `// Auto-generated by scripts/bundle-p5.mjs. Do not edit.\nexport const p5Version = "${version}";\n`;
  fs.writeFileSync(P5_VERSION_FILE, file, "utf-8");
}

async function main() {
  console.log(`[bundle-p5] p5.js version: ${PINNED_P5_VERSION}`);
  console.log(`[bundle-p5] Fetching ${CDN_URL}`);
  const src = await download(CDN_URL);
  writeP5Source(src);
  writeP5Version(PINNED_P5_VERSION);
  console.log(`[bundle-p5] Wrote ${P5_SOURCE_FILE} (${src.length} bytes)`);
  console.log(`[bundle-p5] Wrote ${P5_VERSION_FILE}`);
}

main().catch((err) => {
  console.error("[bundle-p5] FAILED:", err);
  process.exit(1);
});
