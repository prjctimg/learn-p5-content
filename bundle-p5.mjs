#!/usr/bin/env node
// Bundles the pinned p5.js distribution into a string literal for the app.
// Produces two files:
//   - ./p5Source.ts   (the transpiled p5 library as a string literal)
//   - ./p5Version.ts  (the resolved version string)
//
// p5 2.4 ships an ES2022 bundle. Expo supports older Android WebViews, so the
// runtime is transpiled to ES2015 and prefixed with a small ES5 compatibility
// shim. The shim lives in the content pack so already-installed app versions
// recover as soon as they download the updated pack.

import fs from "fs";
import path from "path";
import https from "https";
import { fileURLToPath } from "url";
import { transform } from "esbuild";
import { parse } from "acorn";
import { PINNED_P5_VERSION } from "./p5-version.mjs";
import {
  P5_RUNTIME_COMPAT,
  P5_RUNTIME_COMPAT_MARKER,
} from "./p5-runtime-compat.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = __dirname;

const P5_SOURCE_FILE = path.join(ROOT, "./p5Source.ts");
const P5_VERSION_FILE = path.join(ROOT, "./p5Version.ts");
const CDN_URL = `https://cdn.jsdelivr.net/npm/p5@${PINNED_P5_VERSION}/lib/p5.min.js`;
const P5_BANNER_RE = /^\/\*![\s\S]*?\*\//;

function download(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, (res) => {
        if (res.statusCode && res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
          return download(res.headers.location).then(resolve).catch(reject);
        }
        if (res.statusCode !== 200) {
          return reject(new Error(`HTTP ${res.statusCode} fetching ${url}`));
        }
        const chunks = [];
        res.on("data", (d) => chunks.push(d));
        res.on("end", () => resolve(Buffer.concat(chunks).toString("utf8")));
      })
      .on("error", reject);
  });
}

function writeP5Source(src) {
  const chunks = [];
  const max = 200_000;
  for (let i = 0; i < src.length; i += max) {
    chunks.push(JSON.stringify(src.slice(i, i + max)));
  }
  const file =
    `// Auto-generated by bundle-p5.mjs. Do not edit.\n` +
    `// Pinned p5.js version: ${PINNED_P5_VERSION}\n\n` +
    `const _p = [\n  ${chunks.join(",\n  ")}\n];\n\n` +
    `export const p5Source: string = _p.join("");\n`;
  fs.writeFileSync(P5_SOURCE_FILE, file, "utf-8");
}

function writeP5Version(version) {
  const file = `// Auto-generated by bundle-p5.mjs. Do not edit.\nexport const p5Version = "${version}";\n`;
  fs.writeFileSync(P5_VERSION_FILE, file, "utf-8");
}

async function buildRuntime(source) {
  const bannerMatch = source.match(P5_BANNER_RE);
  if (!bannerMatch) {
    throw new Error("p5.js download is missing its version banner.");
  }
  if (!bannerMatch[0].includes(`p5.js v${PINNED_P5_VERSION}`)) {
    throw new Error(`p5.js banner does not match pinned version ${PINNED_P5_VERSION}.`);
  }

  const body = source.slice(bannerMatch[0].length);
  const transformed = await transform(body, {
    loader: "js",
    target: "es2015",
    minify: true,
    charset: "utf8",
    legalComments: "inline",
  });

  const runtime = `${bannerMatch[0]}\n${P5_RUNTIME_COMPAT}\n${transformed.code}\n`;
  validateRuntime(runtime);
  return runtime;
}

function validateRuntime(runtime) {
  if (!runtime.startsWith(`/*! p5.js v${PINNED_P5_VERSION}`)) {
    throw new Error("Transpiled p5.js runtime lost its version banner.");
  }
  if (!runtime.includes(P5_RUNTIME_COMPAT_MARKER)) {
    throw new Error("Transpiled p5.js runtime is missing its compatibility shim.");
  }
  if (!runtime.trimEnd().endsWith(");")) {
    throw new Error("Transpiled p5.js runtime is truncated.");
  }

  try {
    parse(runtime, { ecmaVersion: 2015, sourceType: "script" });
  } catch (error) {
    throw new Error(`Transpiled p5.js runtime is not ES2015: ${error.message}`);
  }
}

async function main() {
  console.log(`[bundle-p5] p5.js version: ${PINNED_P5_VERSION}`);
  console.log(`[bundle-p5] Fetching ${CDN_URL}`);
  const source = await download(CDN_URL);
  const runtime = await buildRuntime(source);
  writeP5Source(runtime);
  writeP5Version(PINNED_P5_VERSION);
  console.log(
    `[bundle-p5] Wrote ${P5_SOURCE_FILE} (${runtime.length} bytes, ES2015 + compat shim)`
  );
  console.log(`[bundle-p5] Wrote ${P5_VERSION_FILE}`);
}

main().catch((err) => {
  console.error("[bundle-p5] FAILED:", err);
  process.exit(1);
});
